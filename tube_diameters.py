"""
Standard tube diameters (OD, ID) in inches.
From TEMA standards.
"""


def select_tube(idx):
    """Return (OD_inches, ID_inches) for a standard tube index 1..21."""
    std_diam = {
        1: [1/4, 0.194],
        2: [1/4, 0.206],
        3: [1/2, 0.402],
        4: [1/2, 0.430],
        5: [1/2, 0.444],
        6: [3/4, 0.482],
        7: [3/4, 0.584],
        8: [3/4, 0.620],
        9: [3/4, 0.652],
        10: [1, 0.670],
        11: [1, 0.834],
        12: [1, 0.870],
        13: [1, 0.902],
        14: [1.25, 0.920],
        15: [1.25, 1.084],
        16: [1.25, 1.120],
        17: [1.25, 1.152],
        18: [2, 1.760],
        19: [2, 1.782],
        20: [2, 1.810],
        21: [2, 1.834],
    }
    idx = max(1, min(21, int(idx)))
    return std_diam[idx]
